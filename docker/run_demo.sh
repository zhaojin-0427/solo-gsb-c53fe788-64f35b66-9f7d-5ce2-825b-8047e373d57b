#!/bin/sh
# 一键验收（docker compose --profile demo run --rm demo）：
# 1) 并发回滚竞态回归（进程内真实 ASGI + 真实 PostgreSQL 行锁，故障闸门注入交错）
# 2) 迁移缺片故障转移回归（模拟重启/内存池淘汰后的 failed 终态与安全重试）
# 3) 迁移会话创建并发幂等回归（同键对两条不同有效源记录的预查后交错：
#    恰一次 201、败方稳定 409 IDEMPOTENCY_CONFLICT 且不留下会话、单独拒绝审计；
#    同键同源 200 重放；异键同源 MIGRATION_CONFLICT；非目标 23505/通用故障 500；
#    胜方在败方重读前 open→completed 仍稳定 409、open→failed 终态后败方按重建规则 201）
# 4) 谱系逻辑销毁回归（销毁 × 迁移完成/分片领取/提交 的确定性先后、幂等回执，
#    以及并发复用同一幂等键的回执预查交错：恰一次 201、另一次稳定 409 且整体回滚）
# 5) 完整端到端验收（正常恢复 + 各类拒绝依据 + 并发重放 + 跨策略迁移 + 谱系销毁 + 审计哈希链重放）
set -e

echo "######################################################################"
echo "# 1/5 并发回滚竞态回归 (scripts.race_recovery)"
echo "######################################################################"
python -m scripts.race_recovery

echo
echo "######################################################################"
echo "# 2/5 迁移缺片故障转移回归 (scripts.race_migration)"
echo "######################################################################"
python -m scripts.race_migration

echo
echo "######################################################################"
echo "# 3/5 迁移创建并发幂等回归 (scripts.race_migration_start)"
echo "######################################################################"
python -m scripts.race_migration_start

echo
echo "######################################################################"
echo "# 4/5 谱系逻辑销毁回归 (scripts.race_destruction)"
echo "######################################################################"
python -m scripts.race_destruction

echo
echo "######################################################################"
echo "# 5/5 端到端验收 (scripts.demo)"
echo "######################################################################"
exec python -m scripts.demo
